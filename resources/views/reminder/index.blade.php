    <script>
        document.addEventListener('DOMContentLoaded', function() {
            function getLocalISODate(date) {
                const y = date.getFullYear();
                const m = String(date.getMonth() + 1).padStart(2, '0');
                const d = String(date.getDate()).padStart(2, '0');
                return `${y}-${m}-${d}`;
            }

            const today = new Date();
            today.setHours(0, 0, 0, 0);

            let currentDate = new Date(today.getFullYear(), today.getMonth(), 1);
            let selectedDate = null;
            let reminders = @json($reminders ?? []);

            // DOM Elements
            const calendarGrid = document.getElementById('calendarGrid');
            const miniCalendarGrid = document.getElementById('miniCalendarGrid');
            const currentMonthYear = document.getElementById('currentMonthYear');
            const prevMonthBtn = document.getElementById('prevMonth');
            const nextMonthBtn = document.getElementById('nextMonth');
            const taxDueDateInput = document.getElementById('taxDueDate');
            const vehicleSelect = document.getElementById('vehicleSelect');
            const vehicleTypeToggle = document.getElementById('vehicleTypeToggle');
            const vehicleTypeInput = document.getElementById('vehicleTypeInput');
            const btnMotor = document.getElementById('btnMotor');
            const btnMobil = document.getElementById('btnMobil');
            const reminderDaysToggle = document.getElementById('reminderDaysToggle');
            const reminderDaysInput = document.getElementById('reminderDaysInput');
            const searchInput = document.getElementById('searchVehicle');
            const months = ['Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni', 'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'];

            // Lock vehicle type buttons by default
            unlockVehicleTypeButtons();

            function lockVehicleTypeButtons(activeType) {
                // Reset semua dulu
                btnMotor.classList.remove('locked', 'active');
                btnMobil.classList.remove('locked', 'active');

                // Kunci tombol yang BUKAN tipe aktif
                if (activeType === 'motor') {
                    btnMotor.classList.add('active'); // Motor normal & aktif
                    btnMobil.classList.add('locked'); // Mobil transparan & tidak bisa diklik
                    vehicleTypeInput.value = 'motor';
                } else if (activeType === 'mobil') {
                    btnMobil.classList.add('active'); // Mobil normal & aktif
                    btnMotor.classList.add('locked'); // Motor transparan & tidak bisa diklik
                    vehicleTypeInput.value = 'mobil';
                }
            }

            function unlockVehicleTypeButtons() {
                btnMotor.classList.remove('locked', 'active');
                btnMobil.classList.remove('locked', 'active');
                // Default ke motor
                btnMotor.classList.add('active');
                vehicleTypeInput.value = 'motor';
            }

            function setVehicleType(type) {
                vehicleTypeToggle.querySelectorAll('.rm-toggle-btn').forEach(b => b.classList.remove('active'));
                if (type === 'motor') {
                    btnMotor.classList.add('active');
                    vehicleTypeInput.value = 'motor';
                } else if (type === 'mobil') {
                    btnMobil.classList.add('active');
                    vehicleTypeInput.value = 'mobil';
                }
            }

            // Reminder Days Toggle (always functional)
            reminderDaysToggle.querySelectorAll('.rm-toggle-btn').forEach(btn => {
                btn.addEventListener('click', function() {
                    reminderDaysToggle.querySelectorAll('.rm-toggle-btn').forEach(b => b.classList.remove('active'));
                    this.classList.add('active');
                    reminderDaysInput.value = this.dataset.days;
                });
            });

            // Vehicle Select Change
            vehicleSelect.addEventListener('change', function() {
                const selectedOption = this.options[this.selectedIndex];

                if (selectedOption.value && selectedOption.dataset.taxDate) {
                    taxDueDateInput.value = selectedOption.dataset.taxDate;
                    const [y, m, d] = selectedOption.dataset.taxDate.split('-').map(Number);
                    selectedDate = new Date(y, m - 1, d);
                    selectedDate.setHours(0, 0, 0, 0);

                    currentDate = new Date(y, m - 1, 1);

                    // Lock type sesuai data kendaraan
                    const vehicleType = selectedOption.dataset.type;
                    if (vehicleType) {
                        lockVehicleTypeButtons(vehicleType);
                    }

                    updateMonthYear();
                    renderCalendar();
                    renderMiniCalendar();
                } else {
                    taxDueDateInput.value = '';
                    selectedDate = null;
                    unlockVehicleTypeButtons();
                    renderCalendar();
                    renderMiniCalendar();
                }
            });

            // Calendar Navigation
            prevMonthBtn.addEventListener('click', () => {
                currentDate.setMonth(currentDate.getMonth() - 1);
                updateMonthYear();
                renderCalendar();
                renderMiniCalendar();
            });

            nextMonthBtn.addEventListener('click', () => {
                currentDate.setMonth(currentDate.getMonth() + 1);
                updateMonthYear();
                renderCalendar();
                renderMiniCalendar();
            });

            // Search
            searchInput.addEventListener('input', function() {
                const query = this.value.toLowerCase();
                const eventBlocks = document.querySelectorAll('.rm-event-block');
                eventBlocks.forEach(block => {
                    const text = block.textContent.toLowerCase();
                    block.style.opacity = text.includes(query) ? '1' : '0.3';
                });
            });

            // View Tabs
            document.querySelectorAll('.rm-view-tab').forEach(tab => {
                tab.addEventListener('click', function() {
                    document.querySelectorAll('.rm-view-tab').forEach(t => t.classList.remove('active'));
                    this.classList.add('active');
                });
            });

            // Cancel Button
            document.getElementById('btnCancel').addEventListener('click', function() {
                document.getElementById('reminderForm').reset();
                selectedDate = null;
                taxDueDateInput.value = '';

                unlockVehicleTypeButtons(); // Unlock semua, default motor aktif

                reminderDaysToggle.querySelectorAll('.rm-toggle-btn').forEach(b => b.classList.remove('active'));
                reminderDaysToggle.querySelector('[data-days="3"]').classList.add('active');
                reminderDaysInput.value = '3';

                currentDate = new Date(today.getFullYear(), today.getMonth(), 1);
                updateMonthYear();
                renderCalendar();
                renderMiniCalendar();
            });

            // Add Button
            document.getElementById('btnAddReminder').addEventListener('click', function() {
                vehicleSelect.focus();
            });

            // Form Submit Validation
            document.getElementById('reminderForm').addEventListener('submit', function(e) {
                if (!vehicleSelect.value) {
                    e.preventDefault();
                    alert('Silakan pilih kendaraan terlebih dahulu.');
                    vehicleSelect.focus();
                }
            });

            // ========== RENDER FUNCTIONS ==========
            function renderCalendar() {
                const year = currentDate.getFullYear();
                const month = currentDate.getMonth();
                const firstDay = new Date(year, month, 1).getDay();
                const daysInMonth = new Date(year, month + 1, 0).getDate();
                const daysInPrevMonth = new Date(year, month, 0).getDate();

                let html = '';

                for (let i = firstDay - 1; i >= 0; i--) {
                    const day = daysInPrevMonth - i;
                    const date = new Date(year, month - 1, day);
                    html += generateCalendarCell(date, day, true);
                }

                for (let day = 1; day <= daysInMonth; day++) {
                    const date = new Date(year, month, day);
                    html += generateCalendarCell(date, day, false);
                }

                const totalCells = firstDay + daysInMonth;
                const remainingCells = totalCells % 7 === 0 ? 0 : 7 - (totalCells % 7);

                for (let day = 1; day <= remainingCells; day++) {
                    const date = new Date(year, month + 1, day);
                    html += generateCalendarCell(date, day, true);
                }

                calendarGrid.innerHTML = html;
            }

            function generateCalendarCell(date, day, isMuted) {
                const dateStr = getLocalISODate(date);
                const dateTime = date.getTime();
                const isToday = dateTime === today.getTime();
                const isSelected = selectedDate && dateTime === selectedDate.getTime();
                const eventsOnDate = reminders.filter(r => {
                    if (!r.tanggal) return false;
                    return r.tanggal.substring(0, 10) === dateStr;
                });
                const hasEvent = eventsOnDate.length > 0;
                const isOverdue = hasEvent && dateTime < today.getTime();

                let cellClass = 'rm-cal-cell';
                if (isToday) cellClass += ' today';
                if (isSelected) cellClass += ' selected';
                if (hasEvent) cellClass += ' has-event';

                let html = `<div class="${cellClass}" data-date="${dateStr}">`;
                html += '<div class="rm-date-top">';
                if (hasEvent && !isMuted) {
                    html += '<div class="rm-event-dot"></div>';
                }
                html += `<div class="rm-date-num${isMuted ? ' muted' : ''}">${day}</div>`;
                html += '</div>';

                if (hasEvent && !isMuted) {
                    eventsOnDate.forEach(event => {
                        const overdueClass = isOverdue ? ' overdue' : '';
                        const noPolisi = event.vehicle?.no_polisi || event.no_polisi || 'Kendaraan';
                        const jenis = event.vehicle?.jenis || event.jenis || '';
                        html += `<div class="rm-event-block${overdueClass}" title="${noPolisi}">`;
                        html += `Pajak ${jenis}<br>(${noPolisi})`;
                        html += '</div>';
                    });
                }

                html += '</div>';
                return html;
            }

            function renderMiniCalendar() {
                const year = currentDate.getFullYear();
                const month = currentDate.getMonth();
                const days = ['Min', 'Sen', 'Sel', 'Rab', 'Kam', 'Jum', 'Sab'];
                let html = '';

                days.forEach(day => html += `<div class="rm-mini-day">${day}</div>`);

                const firstDay = new Date(year, month, 1).getDay();
                const daysInMonth = new Date(year, month + 1, 0).getDate();
                const daysInPrevMonth = new Date(year, month, 0).getDate();

                for (let i = firstDay - 1; i >= 0; i--) {
                    html += `<div class="rm-mini-date muted">${daysInPrevMonth - i}</div>`;
                }

                for (let day = 1; day <= daysInMonth; day++) {
                    const date = new Date(year, month, day);
                    const dateStr = getLocalISODate(date);
                    const dateTime = date.getTime();
                    const isToday = dateTime === today.getTime();
                    const isSelected = selectedDate && dateTime === selectedDate.getTime();
                    const hasEvent = reminders.some(r => {
                        if (!r.tanggal) return false;
                        return r.tanggal.substring(0, 10) === dateStr;
                    });

                    let dateClass = 'rm-mini-date';
                    if (isToday) dateClass += ' solid';
                    else if (isSelected) dateClass += ' outline';
                    else if (hasEvent) dateClass += ' has-event';

                    html += `<div class="${dateClass}">${day}</div>`;
                }

                const totalCells = firstDay + daysInMonth;
                const remainingCells = totalCells % 7 === 0 ? 0 : 7 - (totalCells % 7);

                for (let day = 1; day <= remainingCells; day++) {
                    html += `<div class="rm-mini-date muted">${day}</div>`;
                }

                miniCalendarGrid.innerHTML = html;
            }

            function updateMonthYear() {
                currentMonthYear.textContent = `${months[currentDate.getMonth()]} ${currentDate.getFullYear()}`;
            }

            // Initial Render
            // If first vehicle has tax date, auto-select it
            if (vehicleSelect.options.length > 1 && vehicleSelect.options[1].value) {
                // Don't auto-select, let user choose
            }

            renderCalendar();
            renderMiniCalendar();
            updateMonthYear();
        });
    </script>
